//! `fixed_set!` and `fixed_map!`: fixed-capacity associative containers
//! generated as a module of concrete `LogicValue` types and `#[logic]`
//! functions. Lookups compare the key against every slot in parallel.
use crate::error;
use proc_macro2::{Literal, TokenStream as Tokens};
use quote::quote;
use syn::{
    Ident, LitInt, Token, Type, Visibility,
    parse::{Parse, ParseStream},
};

/// `[pub] mod name: Key [=> Value], capacity = N`
pub struct Spec {
    vis: Visibility,
    name: Ident,
    key: Type,
    value: Option<Type>,
    capacity: LitInt,
}

impl Parse for Spec {
    fn parse(input: ParseStream) -> syn::Result<Self> {
        let vis = input.parse()?;
        input.parse::<Token![mod]>()?;
        let name = input.parse()?;
        input.parse::<Token![:]>()?;
        let key = input.parse()?;
        let value = if input.peek(Token![=>]) {
            input.parse::<Token![=>]>()?;
            Some(input.parse()?)
        } else {
            None
        };
        input.parse::<Token![,]>()?;
        let label: Ident = input.parse()?;
        if label != "capacity" {
            return Err(error(label, "expected `capacity = N`"));
        }
        input.parse::<Token![=]>()?;
        let capacity = input.parse()?;
        input.parse::<Option<Token![,]>>()?;
        Ok(Spec {
            vis,
            name,
            key,
            value,
            capacity,
        })
    }
}

fn lit(n: u64) -> Literal {
    Literal::u64_unsuffixed(n)
}

/// Bits needed to hold `n`.
fn width_of(n: u64) -> u64 {
    (64 - n.leading_zeros() as u64).max(1)
}

pub fn expand(spec: Spec, map: bool) -> syn::Result<Tokens> {
    let Spec {
        vis,
        name,
        key,
        value,
        capacity,
    } = spec;
    match (&value, map) {
        (Some(v), false) => return Err(error(v, "fixed_set! takes a key type only")),
        (None, true) => return Err(error(&key, "fixed_map! needs `Key => Value`")),
        _ => {}
    }
    crate::value_type(&key)?;
    if let Some(v) = &value {
        crate::value_type(v)?;
    }
    let n: u64 = capacity.base10_parse()?;
    if !(1..=256).contains(&n) {
        return Err(error(&capacity, "capacity must be in 1..=256"));
    }
    let cap = lit(n);
    let index_width = lit(width_of(n - 1));
    let count_width = lit(width_of(n));
    let zero = lit(0);
    let one = lit(1);
    // A power-of-two capacity wraps for free; otherwise wrap at the last slot.
    let advance = if n.is_power_of_two() {
        quote!(m.next + bits::<#index_width>(#one))
    } else {
        let last = lit(n - 1);
        quote!(if m.next == bits::<#index_width>(#last) {
            bits::<#index_width>(#zero)
        } else {
            m.next + bits::<#index_width>(#one)
        })
    };
    let (container, kind) = if map {
        (quote!(Map), "map")
    } else {
        (quote!(Set), "set")
    };
    // Map-only pieces: the value field, its parameters and arguments.
    let value_field = value.as_ref().map(|v| quote!(pub value: #v,));
    let value_param = value.as_ref().map(|v| quote!(, value: #v));
    let value_arg = value.as_ref().map(|_| quote!(, value));
    let value_keep = value.as_ref().map(|_| quote!(value: e.value,));
    let value_alias = value.as_ref().map(|v| quote!(pub type Value = #v;));
    let map_only = value.as_ref().map(|v| {
        quote! {
            #[derive(Clone, Copy, Debug, PartialEq, Eq, LogicValue)]
            pub struct Lookup {
                pub hit: bool,
                /// Meaningful only when `hit`.
                pub value: #v,
            }

            /// The value stored for `key`.
            #[logic]
            pub fn get(m: Map, key: #key) -> Lookup {
                let f = find(m, key);
                Lookup { hit: f.hit, value: m.entries.at(f.index).value }
            }

            /// Overwrite the value of a present `key`; never adds.
            #[logic]
            pub fn update(m: Map, enable: bool, key: #key, value: #v) -> Map {
                store(m, find(m, key), enable, false, key, value)
            }
        }
    });
    // Sets have nothing to refresh: a present key is left as it is.
    let (refresh_param, refresh_arg, write) = if map {
        (
            quote!(refresh: bool,),
            quote!(enable,),
            quote!(if found.hit { refresh } else { add }),
        )
    } else {
        (quote!(), quote!(), quote!(!found.hit && add))
    };
    let doc = format!(
        "Fixed-capacity {kind} of {n} entries generated by `fixed_{kind}!`. \
         Lookups compare the key with every slot in parallel. Adding a key \
         fills the first vacant slot; when none is vacant the slot at `next` \
         is replaced and `next` advances, so replacement is round-robin."
    );
    Ok(quote! {
        #[doc = #doc]
        #vis mod #name {
            #![allow(unused_imports, dead_code)]
            use super::*;
            use ::bitlogic::{Bits, LogicValue, bits, logic};

            pub const CAPACITY: usize = #cap;
            pub type Key = #key;
            #value_alias
            pub type Index = Bits<#index_width>;
            pub type Count = Bits<#count_width>;

            #[derive(Clone, Copy, Debug, PartialEq, Eq, LogicValue)]
            pub struct Entry {
                pub valid: bool,
                pub key: #key,
                #value_field
            }

            /// All slots plus the next slot to replace when full. The zero
            /// value is empty.
            #[derive(Clone, Copy, Debug, PartialEq, Eq, LogicValue)]
            pub struct #container {
                pub entries: [Entry; #cap],
                pub next: Bits<#index_width>,
            }

            /// The first slot that matched, if any.
            #[derive(Clone, Copy, Debug, PartialEq, Eq, LogicValue)]
            pub struct Found {
                pub hit: bool,
                pub index: Bits<#index_width>,
            }

            /// The slot holding `key`, if any.
            #[logic]
            pub fn find(m: #container, key: #key) -> Found {
                Found { hit: false, index: bits::<#index_width>(#zero) }.fold::<#cap>(|acc, k| {
                    let e = m.entries.at(k);
                    let here = !acc.hit && e.valid && e.key == key;
                    Found {
                        hit: acc.hit || here,
                        index: if here { k.slice::<#index_width>(0) } else { acc.index },
                    }
                })
            }

            /// The first vacant slot, if any.
            #[logic]
            pub fn vacant(m: #container) -> Found {
                Found { hit: false, index: bits::<#index_width>(#zero) }.fold::<#cap>(|acc, k| {
                    let here = !acc.hit && !m.entries.at(k).valid;
                    Found {
                        hit: acc.hit || here,
                        index: if here { k.slice::<#index_width>(0) } else { acc.index },
                    }
                })
            }

            #[logic]
            pub fn contains(m: #container, key: #key) -> bool {
                find(m, key).hit
            }

            /// Write `key` given an earlier `find(m, key)`, so a caller that
            /// already looked the key up shares that lookup. A present key
            /// is rewritten when `refresh` (maps only); an absent key is
            /// added when `add`.
            #[logic]
            pub fn store(m: #container, found: Found, #refresh_param add: bool, key: #key #value_param) -> #container {
                let gap = vacant(m);
                let slot = if found.hit {
                    found.index
                } else if gap.hit {
                    gap.index
                } else {
                    m.next
                };
                let write = #write;
                let replace = !found.hit && add && !gap.hit;
                #container {
                    entries: if write {
                        m.entries.set(slot, Entry { valid: true, key #value_arg })
                    } else {
                        m.entries
                    },
                    next: if replace { #advance } else { m.next },
                }
            }

            /// Add `key` (maps: or overwrite its value) when `enable`.
            #[logic]
            pub fn insert(m: #container, enable: bool, key: #key #value_param) -> #container {
                store(m, find(m, key), #refresh_arg enable, key #value_arg)
            }

            /// Remove `key` when `enable`. The slot becomes vacant.
            #[logic]
            pub fn remove(m: #container, enable: bool, key: #key) -> #container {
                let f = find(m, key);
                let e = m.entries.at(f.index);
                #container {
                    entries: if enable && f.hit {
                        m.entries.set(f.index, Entry { valid: false, key: e.key, #value_keep })
                    } else {
                        m.entries
                    },
                    next: m.next,
                }
            }

            /// Number of occupied slots.
            #[logic]
            pub fn count(m: #container) -> Bits<#count_width> {
                bits::<#count_width>(#zero).fold::<#cap>(|n, k| {
                    if m.entries.at(k).valid { n + bits::<#count_width>(#one) } else { n }
                })
            }

            #map_only
        }
    })
}
